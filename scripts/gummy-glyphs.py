"""Extract Fredoka Bold outlines for the homepage gummy letters.

Usage: python3 scripts/gummy-glyphs.py path/to/Fredoka[wdth,wght].ttf > app/components/gummy/glyphs.ts
Fredoka is licensed under the SIL Open Font License 1.1.
"""
import json
import sys

from fontTools.pens.basePen import BasePen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.varLib.instancer import instantiateVariableFont

WORD = "Jacob"
STEPS = 8  # samples per curve segment


class FlattenPen(BasePen):
    def __init__(self, glyphSet):
        super().__init__(glyphSet)
        self.contours = []
        self.current = None

    def _moveTo(self, pt):
        self.current = [pt]

    def _lineTo(self, pt):
        self.current.append(pt)

    def _curveToOne(self, p1, p2, p3):
        p0 = self._getCurrentPoint()
        for i in range(1, STEPS + 1):
            t = i / STEPS
            mt = 1 - t
            self.current.append(
                tuple(
                    mt**3 * a + 3 * mt * mt * t * b + 3 * mt * t * t * c + t**3 * d
                    for a, b, c, d in zip(p0, p1, p2, p3)
                )
            )

    def _qCurveToOne(self, p1, p2):
        p0 = self._getCurrentPoint()
        for i in range(1, STEPS + 1):
            t = i / STEPS
            mt = 1 - t
            self.current.append(
                tuple(mt * mt * a + 2 * mt * t * b + t * t * c for a, b, c in zip(p0, p1, p2))
            )

    def _closePath(self):
        pts = self.current
        if len(pts) > 1 and pts[0] == pts[-1]:
            pts = pts[:-1]
        self.contours.append(pts)
        self.current = None

    _endPath = _closePath


font = instantiateVariableFont(TTFont(sys.argv[1]), {"wght": 700, "wdth": 100})
cmap = font.getBestCmap()
# Variable fonts draw stems and bowls as overlapping contours; merge them so
# each glyph is a clean outline plus its counters.
removeOverlaps(font, [cmap[ord(ch)] for ch in WORD])
glyph_set = font.getGlyphSet()
upm = font["head"].unitsPerEm
hhea = font["hhea"]

glyphs = []
x = 0
for ch in WORD:
    name = cmap[ord(ch)]
    advance = font["hmtx"][name][0]
    svg = SVGPathPen(glyph_set)
    glyph_set[name].draw(svg)
    flat = FlattenPen(glyph_set)
    glyph_set[name].draw(flat)
    glyphs.append(
        {
            "char": ch,
            "x": x,
            "advance": advance,
            # Font units, y up. Consumers flip y.
            "path": svg.getCommands(),
            "contours": [[[round(px, 1), round(py, 1)] for px, py in c] for c in flat.contours],
        }
    )
    x += advance

print("// Generated by scripts/gummy-glyphs.py from Fredoka Bold (SIL Open Font License 1.1).")
print("// Coordinates are font units with y pointing up.")
print()
print("export interface GummyGlyph {")
print("  char: string;")
print("  x: number;")
print("  advance: number;")
print("  path: string;")
print("  contours: [number, number][][];")
print("}")
print()
print(f"export const UNITS_PER_EM = {upm};")
print(f"export const ASCENT = {hhea.ascent};")
print(f"export const DESCENT = {hhea.descent};")
print(f"export const ADVANCE = {x};")
print()
print("export const GLYPHS: GummyGlyph[] = " + json.dumps(glyphs, separators=(",", ":")) + ";")
